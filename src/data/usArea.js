export const US_AREA_RINGS = Object.freeze(
  [
    ...US_OUTLINE_PARTS.map((flat) => {
      const ring = [];
      for (let i = 0; i + 1 < flat.length; i += 2)
        ring.push([flat[i], flat[i + 1]]);
      return ring;
    }),
    ...US_ISLAND_BOXES.map(boxRing),
  ].map((ring) => Object.freeze({ ring, bbox: bboxOf(ring) })),
);

const boxesOverlap = (a, b) =>
  a[0] <= b[2] && b[0] <= a[2] && a[1] <= b[3] && b[1] <= a[3];

/** Even-odd test; ring is open or closed [[lon, lat], …]. */
function pointInRing([x, y], ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i, i += 1) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi)
      inside = !inside;
  }
  return inside;
}

const cross = (o, a, b) =>
  (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0]);

/** Whether segments pq and rs properly cross or touch. */
function segmentsMeet(p, q, r, s) {
  const d1 = cross(r, s, p);
  const d2 = cross(r, s, q);
  const d3 = cross(p, q, r);
  const d4 = cross(p, q, s);
  if (
    ((d1 > 0 && d2 < 0) || (d1 < 0 && d2 > 0)) &&
    ((d3 > 0 && d4 < 0) || (d3 < 0 && d4 > 0))
  )
    return true;
  const onSegment = (a, b, c) =>
    Math.min(a[0], b[0]) <= c[0] &&
    c[0] <= Math.max(a[0], b[0]) &&
    Math.min(a[1], b[1]) <= c[1] &&
    c[1] <= Math.max(a[1], b[1]);
  return (
    (d1 === 0 && onSegment(r, s, p)) ||
    (d2 === 0 && onSegment(r, s, q)) ||
    (d3 === 0 && onSegment(p, q, r)) ||
    (d4 === 0 && onSegment(p, q, s))
  );
}

function ringsIntersect(a, b) {
  if (a.some((point) => pointInRing(point, b))) return true;
  if (b.some((point) => pointInRing(point, a))) return true;
  for (let i = 0, j = a.length - 1; i < a.length; j = i, i += 1) {
    for (let k = 0, l = b.length - 1; k < b.length; l = k, k += 1) {
      if (segmentsMeet(a[j], a[i], b[l], b[k])) return true;
    }
  }
  return false;
}

/**
 * Whether a smoke polygon (an outer ring of [lon, lat]) overlaps or touches
 * any part of the US area.
 * @param {Array<[number, number]>} ring
 * @returns {boolean}
 */
export function ringTouchesUs(ring) {
  if (!Array.isArray(ring) || ring.length < 3) return false;
  const bbox = bboxOf(ring);
  return US_AREA_RINGS.some(
    (part) => boxesOverlap(bbox, part.bbox) && ringsIntersect(ring, part.ring),
  );
}
